"""Write static/dtc-data.js from obd/dtc/ (trouble code titles and troubleshooting help).

Run after changing anything in obd/dtc/:  python tools/build_dtcs.py
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from obd.dtcs import load, validate  # noqa: E402

data = load()
errors = validate(data)
if errors:
    sys.exit("\n".join(errors))
out = ROOT / "static" / "dtc-data.js"
out.write_text("// Generated by tools/build_dtcs.py from obd/dtc/, do not edit by hand.\n"
               f"const OBD_DTC_DATA = {json.dumps(data, ensure_ascii=False, separators=(',', ':'))};\n", encoding="utf-8")
n_make = sum(len(g["codes"]) for g in data["makes"]["groups"].values())
print(f"wrote {out} ({len(data['generic'])} generic codes, {n_make} manufacturer codes, {len(data['help'])} help entries)")
