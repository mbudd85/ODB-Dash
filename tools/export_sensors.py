"""Write static/phone/sensors.js from obd/pids.py, obd/vehicles/*.json and obd/profiles.json.

The phone version has no Python, so it gets the sensor list as a JS file.
Run after changing sensors:  python tools/export_sensors.py
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from obd.pids import PID_LENGTHS, Registry  # noqa: E402

reg = Registry()
assert not reg.errors, reg.errors
out = ROOT / "static" / "phone" / "sensors.js"
data = json.dumps(reg.catalog(), ensure_ascii=False, indent=1)
profiles = json.dumps(json.loads((ROOT / "obd" / "profiles.json").read_text(encoding="utf-8")), ensure_ascii=False, indent=1)
out.write_text("// Generated by tools/export_sensors.py, do not edit by hand.\n"
               f"const OBD_SENSORS = {data};\n"
               f"const OBD_PROFILES = {profiles};\n"
               f"const OBD_PID_LENGTHS = {json.dumps(PID_LENGTHS, sort_keys=True)};\n", encoding="utf-8")
print(f"wrote {out} ({len(reg.catalog())} sensors)")
